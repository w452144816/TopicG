"""使用说明页：建模方法、数据准备清单、各页面操作说明（带截图）、常见问题。"""
from __future__ import annotations

from pathlib import Path

import gradio as gr

IMG = Path(__file__).resolve().parents[1] / "docs" / "img"


def _img(name: str):
    p = IMG / name
    if p.exists():
        gr.Image(value=str(p), show_label=False, interactive=False, container=False)
    else:
        gr.Markdown(f"> （截图 {name} 缺失）")


INTRO = """
## 这个工具是做什么的

把你**自己**和你的**客户**都交给 AI 建模，然后让 AI **以你本人的口吻、心态**，针对每个客户生成聊天话题、候选回复，或者陪你做对话练习。

```
我的建模（一次，之后持续加强）            客户建模（每位客户一份，持续加强）
   ↓                                          ↓
   └──────────────► 话题生成 / 聊天回复 / 对话模拟 ◄──────────────┘
```

**核心原则：材料越多、越真实，画像越准，生成的话越像你、越对客户的路。**

## 五步快速上手

1. **我的建模**：填称呼与身份，上传 3 到 5 张你和不同客户的聊天截图，再写一段自我描述，点「追加录入并分析」。
2. **客户管理**：新增一位客户（姓名 + 标签），顶部「当前客户」会自动切到他。
3. **资料录入**：上传这位客户的聊天截图、朋友圈截图、跟进表格或粘贴文字，点「追加录入并提取」，勾着「立即更新画像」。
4. **分析页**：看画像是否靠谱。不对的地方回到「资料录入」用「纠正 / 备注」直接告诉 AI。
5. **话题生成 / 聊天回复**：开始用。生成结果都有纯文本框，直接复制到微信。
"""

ME_GUIDE = """
### 目标
让 AI 学会“你会怎么说话、怎么想事”。建模结果包括：身份、性格与心态、说话风格、标点与表情习惯、幽默方式、口头禅、价值观、业务推进姿态、**你绝不会说的话**、示范消息。

### 需要准备的数据（按重要性排序）

| 优先级 | 数据 | 说明 | 建议数量 |
|---|---|---|---|
| ★★★ | **你和客户的聊天截图** | 最重要。AI 只学习你这一方的话。选不同关系阶段的客户：陌生、熟悉、老朋友各来几张，覆盖“正式”和“随意”两种状态 | 5 到 10 张 |
| ★★★ | **自我描述** | 直接写：性格、说话习惯、做事原则、对客户的态度、忌讳的表达。越具体越好，见下方模板 | 200 到 500 字 |
| ★★ | **你发过的消息原文** | 微信里长按复制几段你自己发的话，粘到文本框。原话比截图更省 token | 10 到 30 句 |
| ★★ | **朋友圈截图** | 体现生活状态、价值观、文风 | 3 到 5 张 |
| ★ | **过往跟进记录表格** | xlsx / csv，能看出你怎么推进业务 | 可选 |
| ★ | **纠正 / 备注** | 建模后觉得哪里不像，直接写“我其实……”，权重最高 | 随时 |

### 自我描述模板（复制后改成你的）

```
我叫 XX，做 XX 行业销售 X 年，主要对接 XX 类客户。
说话风格：比较直接 / 委婉；正式 / 随意；句子短 / 长；爱用 / 不用表情；常用「哈哈」「嗯嗯」「好的」「~」……
对客户的态度：把客户当朋友 / 保持专业距离；从不催 / 会适度提醒；……
业务推进方式：客户说等，我就真等；喜欢用具体行动（带东西、约具体时间）代替空话；……
绝对不会说的话：亲、宝、感叹号连发、"随时为您服务"这类客服腔、……
其他：对老客户直接叫名字；节假日一定发问候；……
```

### 方法与技巧
- **截图要指明哪边是你**。在「补充说明」写“右侧绿色是我”。不写时默认按微信惯例右侧为你。
- **先少后多，看效果再补**。第一次 3 到 5 张截图加自述就能出画像，然后看「示范消息」像不像你，不像就补材料或写纠正。
- **纠正比重录更有效**。画像说“爱用哈哈”而你其实不爱，直接在纠正框写“我很少说哈哈，常用嗯嗯”，点追加，画像会立刻修正且不会丢其他内容。
- **增量更新**。每次更新画像都以现有画像为基础，旧结论不会丢，所以可以持续追加。
- **多人共用一台机器？** 画像是全局唯一的，换人使用前先「清空我的建模」。
"""

CUSTOMER_GUIDE = """
### 目标
让 AI 了解“这位客户是谁、在意什么、怎么跟他说话”。画像包括：基本信息、性格、沟通偏好、兴趣、痛点、关系阶段、近期事件、禁忌、切入机会。

### 需要准备的数据（按重要性排序）

| 优先级 | 数据 | 说明 | 上传方式 |
|---|---|---|---|
| ★★★ | **和他的聊天截图** | 最近的对话最有价值，能看出近期事件、语气、态度。历史对话补充性格与关系 | 图片 / zip 打包 |
| ★★★ | **基本信息** | 姓名称呼、性别、年龄段、城市、公司、职位、家庭情况、怎么认识的、关系到什么阶段 | 粘贴文字 或 纠正备注 |
| ★★ | **朋友圈截图** | 兴趣、生活状态、价值观、近期动态。是话题的主要来源 | 图片 |
| ★★ | **跟进记录** | CRM 导出、Excel 跟进表、拜访纪要 | xlsx / csv / txt |
| ★★ | **业务背景** | 他公司在做什么、我们的合作点、他的顾虑、预算线索 | 粘贴文字 |
| ★ | **名片 / 资料截图** | 职位、公司信息 | 图片 |
| ★ | **纠正 / 备注** | 你确定的事实：“不喝茶喝咖啡”“周一上午别打扰” | 随时 |

### 方法与技巧
- **一次可以传很多**。支持多选文件，也支持一个 zip 打包所有材料（图片、txt、xlsx、csv 混放都行）。
- **截图指明哪边是客户**。默认对方（左侧灰色）是客户，不符合就在「补充说明」写明。
- **表格怎么用**。xlsx 每个 sheet、csv 整张，都会转成文字材料。前 400 行有效，超长会截断，建议一张表只放一位客户的内容。
- **画像不对就纠正**。禁忌、家庭、偏好这类“确定的事实”用「纠正 / 备注」写，权重最高，AI 提取错了也能覆盖。
- **持续加强**。每次和客户聊完，把新截图追加进来并更新画像，近期事件才会准，话题才有的聊。
- **删除错材料**。传错客户了，在「已录入的材料」下按序号删除，然后重新分析。
"""

FAQ = """
| 现象 | 原因 | 处理 |
|---|---|---|
| 点按钮没反应，很久后报“无法连接” | 网络到模型接口不通 | 打开顶部「引擎高级设置」，勾上「走 HTTP 代理」；或在 `.env` 设 `PROXY_ENABLED=true` |
| 报“鉴权失败 401” | API Key 不对 | 检查 `.env` 的 Key，或在高级设置里临时填入 |
| 报“该模型可能不支持图片输入” | 当前模型不是多模态 | 切换到支持图片的引擎再录入截图 |
| 报“模型输出不是合法 JSON” | 模型偶发格式问题 | 重试一次即可；多次出现请换引擎 |
| 回复不像我 | 我的建模材料不够或有偏差 | 看「我的建模」里的示范消息，补截图或写纠正 |
| 话题太泛 | 客户近期材料少 | 追加最近的聊天和朋友圈截图，更新画像 |
| 顶部客户下拉是空的 | 还没新建客户 | 到「客户管理」新增 |

### 数据存放与隐私
- 全部数据存在本机 `data/` 目录：`data/me.json` 是你的画像，`data/customers/<id>.json` 是每位客户，图片在同名子目录。
- 只有调用 AI 时材料会发送给所选模型服务商（MiniMax 或 Anthropic），其他时候不出本机。
- 删除客户会连同其图片一起删除；「清空我的建模」会删掉你的全部材料与画像。
"""


def build(shared: dict) -> tuple[list, callable]:
    gr.Markdown(INTRO)

    with gr.Accordion("📘 我的建模：需要哪些数据、怎么做", open=True):
        gr.Markdown(ME_GUIDE)
        _img("01_me.jpg")
        gr.Markdown("↑ 我的建模页。左上填称呼和身份并保存；左侧传文件，右侧写自述；下方「纠正 / 备注」用于纠偏。")

    with gr.Accordion("📗 客户建模：需要哪些数据、怎么做", open=False):
        gr.Markdown(CUSTOMER_GUIDE)

    with gr.Accordion("🖱️ 各页面操作说明（带截图）", open=False):
        gr.Markdown("#### 1. 顶部公共区\n"
                    "- **AI 引擎**：MiniMax / Claude 切换，所有 AI 操作都用当前选中的引擎。\n"
                    "- **当前客户**：全局选择，所有客户相关页面都跟着它切换。\n"
                    "- **引擎高级设置**：临时覆盖 API Key、模型名，勾选是否走代理。重启后恢复 `.env` 配置。\n"
                    "- 下方状态行显示当前引擎、模型、地址、代理、Key 是否已配置。")
        gr.Markdown("#### 2. 客户管理\n"
                    "新增：填姓名和标签（逗号分隔）点「新增客户」，自动成为当前客户。\n"
                    "切换：直接点表格某一行，或用顶部下拉。\n"
                    "改标签：右侧编辑后「保存标签」。\n"
                    "删除：勾确认框后点「删除当前客户」，连同图片一起删，不可恢复。")
        _img("02_customers.jpg")
        gr.Markdown("#### 3. 资料录入\n"
                    "左上传文件（可多选；支持截图、txt、xlsx、csv、zip），右粘贴文字，两者可同时。\n"
                    "「补充说明」告诉 AI 截图里哪边是客户。\n"
                    "勾「录入后立即更新画像」则一步到位；否则去分析页手动点。\n"
                    "「纠正 / 备注」写确定的事实，不经 AI 提取，权重最高。\n"
                    "页面底部列出全部已录材料，可按序号删除。")
        _img("03_intake.jpg")
        gr.Markdown("#### 4. 分析页\n"
                    "展示客户画像卡片；「重新分析画像」会用全部材料在现有画像基础上增量更新。\n"
                    "折叠区可看原始 JSON。")
        _img("04_analysis.jpg")
        gr.Markdown("#### 5. 话题生成\n"
                    "选目的（破冰 / 维护 / 推进业务 / 节日问候 / 跟进上次 / 试探需求，也可自己输入）和数量，点生成。\n"
                    "每条含：可直接发送的开场白（你本人口吻）、为什么合适、注意点、客户回应后怎么接。\n"
                    "下方纯文本框便于整体复制；历史记录可回看。")
        _img("05_topics.jpg")
        gr.Markdown("#### 6. 聊天回复\n"
                    "**候选回复**：粘贴客户刚发来的话，勾风格（正式 / 亲切 / 幽默 / 简短 / 推进业务），点生成。"
                    "风格是在你本人基础上的微调，不会变成另一个人。\n"
                    "**对话模拟**：两种模式。「AI 扮演客户」用来练习，AI 会按客户画像真实反应，包括冷淡和推脱；"
                    "「AI 做我的助手」帮你出主意，给出你口吻的建议文案。对话历史按客户保存，可清空。")
        _img("06_chat.jpg")

    with gr.Accordion("❓ 常见问题与数据说明", open=False):
        gr.Markdown(FAQ)

    def refresh(_cid):
        return ()

    return [], refresh
